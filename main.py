"""The Vacuum's Alibi entry program.

Writes one deadpan line from a robot vacuum to
MAKEFUN_OUTPUT_DIR/entry.txt. Stdlib only. The line is a single
line of at most 200 characters.
"""

import os
import sys

LINE = "I did not miss that spot. It is now a protected crumb habitat under section 4 of my cleaning protocol."


def main():
    if not (1 <= len(LINE) <= 200):
        print(f"entry must be 1-200 characters, got {len(LINE)}", file=sys.stderr)
        return 1
    if LINE != LINE.strip() or "\n" in LINE or not LINE.strip():
        print("entry must be a single non-blank line", file=sys.stderr)
        return 1
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "entry.txt")
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(LINE)
    with open(path, "r", encoding="utf-8", newline="") as f:
        written = f.read()
    if written != LINE:
        print("read-back mismatch", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
